/**
 * Runs a learner's Playwright test file in an isolated run directory and turns the JSON
 * report into per-test results with artifacts (screenshots, trace, console/network log).
 *
 * Safety: the file is statically checked first (gate.ts rejects child_process/fs/process/eval/
 * dynamic import…), the Playwright CLI is spawned directly (no shell), with a scrubbed env,
 * a hard wall-clock timeout that kills the whole process group, one worker, and a
 * concurrency cap enforced by the server. In Compose the container itself is non-root,
 * has no published port, and has memory/CPU/pid limits.
 */
import { spawn } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { HUB_TEST_SOURCE } from "./hubTest.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const RUNNER_ROOT = path.resolve(HERE, "..");
export const RUNS_DIR = process.env.PW_RUNS_DIR || path.join(RUNNER_ROOT, ".runs");
export const SUT_URL = (process.env.SUT_URL || "http://localhost:4000").replace(/\/$/, "");
const KEEP_RUNS = Number(process.env.PW_KEEP_RUNS || 40);

export type Preset = "default" | "auth";

export type RunFile = { path: string; content: string };

export type RunOptions = {
  /** Main learner file, relative to tests/ (e.g. "learner.spec.ts" or "auth.setup.ts"). */
  testFile: string;
  code: string;
  supportFiles?: RunFile[];
  repeatEach?: number;
  preset?: Preset;
  /** App bugs to switch on in extra "mutant" projects; a good test must fail against them. */
  mutants?: string[];
  timeoutMs?: number;
  testTimeoutMs?: number;
  /** Byte ranges in `code` holding '@playwright/test' specifiers (from gate.analyze). */
  importRanges?: Array<{ start: number; end: number }>;
};

export type TestRun = { status: string; duration: number; error?: TestError; repeat: number };
export type TestError = { message: string; line?: number; column?: number; file?: string; snippet?: string };
export type LogEntry = { kind: string; text: string; at: number; status?: number; method?: string; url?: string; level?: string };

export type TestResult = {
  id: string;
  title: string;
  titlePath: string[];
  file: string;
  line?: number;
  project: string;
  status: "passed" | "failed" | "flaky" | "skipped" | "timedOut";
  runs: TestRun[];
  durationMs: number;
  error?: TestError;
  screenshots: string[];
  trace?: string;
  log: LogEntry[];
};

export type MutantResult = { bug: string; status: "caught" | "missed" | "not-run"; tests: number };

export type RunReport = {
  runId: string;
  ok: boolean;
  exitCode: number | null;
  timedOut: boolean;
  durationMs: number;
  tests: TestResult[];
  mutants: MutantResult[];
  globalErrors: TestError[];
  stdout: string;
  stderr: string;
};

const SAFE_REL = /^[A-Za-z0-9_][A-Za-z0-9_\-./]*$/;

/** Rejects absolute paths, traversal and odd characters in any file the runner writes. */
export function safeRelPath(p: string): string {
  const norm = path.posix.normalize(p.replace(/\\/g, "/"));
  if (!SAFE_REL.test(norm) || norm.startsWith("../") || norm.includes("/../") || path.posix.isAbsolute(norm) || norm.length > 120) {
    throw new Error(`Unsafe file path: ${p}`);
  }
  return norm;
}

/** Resolves an artifact request inside a run directory, or null if it escapes it. */
export function resolveArtifact(runId: string, rel: string): string | null {
  if (!/^[a-f0-9]{32}$/.test(runId)) return null;
  const base = path.join(RUNS_DIR, runId);
  const target = path.resolve(base, rel);
  if (!target.startsWith(base + path.sep)) return null;
  if (!/\.(png|jpe?g|webp|zip|json|txt|webm)$/i.test(target)) return null;
  return fs.existsSync(target) ? target : null;
}

export function buildConfig(runId: string, o: Required<Pick<RunOptions, "repeatEach" | "preset" | "mutants" | "testTimeoutMs">>): string {
  const mainMatch = "/.*\\.(spec|test)\\.(ts|js)$/";
  const deps = o.preset === "auth" ? `dependencies: ['setup'],` : "";
  const setup = o.preset === "auth"
    ? `{ name: 'setup', testMatch: /.*\\.setup\\.(ts|js)$/, use: { extraHTTPHeaders: { 'x-hub-run': '${runId}' } } },`
    : "";
  const mutants = o.mutants.map((bug) => `{
      name: 'mutant:${bug}', testMatch: ${mainMatch}, dependencies: ['chromium'], repeatEach: 1,
      use: { trace: 'off', screenshot: 'off', extraHTTPHeaders: { 'x-sut-bug': '${bug}', 'x-hub-run': '${runId}-${bug}' } },
    },`).join("\n    ");
  return `// Generated by the hub runner for every run. Learners never edit this file.
import { defineConfig, devices } from '@playwright/test';

export default defineConfig({
  testDir: './tests',
  outputDir: './test-results',
  snapshotPathTemplate: '{testDir}/__screenshots__/{testFilePath}/{arg}{ext}',
  timeout: ${o.testTimeoutMs},
  expect: { timeout: 5000 },
  fullyParallel: false,
  forbidOnly: false,
  retries: 0,
  workers: 1,
  updateSnapshots: 'missing',
  reporter: [['json', { outputFile: 'report.json' }]],
  use: {
    ...devices['Desktop Chrome'],
    baseURL: '${SUT_URL}',
    viewport: { width: 1280, height: 720 },
    trace: 'on',
    screenshot: 'on',
    actionTimeout: 5000,
    navigationTimeout: 10000,
  },
  projects: [
    ${setup}
    {
      name: 'chromium', testMatch: ${mainMatch}, repeatEach: ${o.repeatEach}, ${deps}
      use: { extraHTTPHeaders: { 'x-hub-run': '${runId}' } },
    },
    ${mutants}
  ],
});
`;
}

function stripAnsi(s: string): string {
  // eslint-disable-next-line no-control-regex
  return s.replace(/\u001b\[[0-9;]*m/g, "");
}

function relToRun(runDir: string, abs: string | undefined): string | undefined {
  if (!abs) return undefined;
  const r = path.relative(runDir, abs);
  return r.startsWith("..") ? undefined : r.split(path.sep).join("/");
}

type JsonError = { message?: string; stack?: string; location?: { file: string; line: number; column: number }; snippet?: string };
type JsonResult = {
  status: string; duration: number; errors?: JsonError[]; error?: JsonError; repeatEachIndex?: number;
  attachments?: Array<{ name: string; path?: string; body?: string; contentType: string }>;
};
type JsonTest = { projectName: string; status: string; results: JsonResult[]; repeatEachIndex?: number };
type JsonSpec = { title: string; file: string; line: number; tests: JsonTest[] };
type JsonSuite = { title: string; file: string; specs?: JsonSpec[]; suites?: JsonSuite[] };
type JsonReport = { suites?: JsonSuite[]; errors?: JsonError[] };

function toError(runDir: string, e: JsonError | undefined): TestError | undefined {
  if (!e) return undefined;
  const msg = stripAnsi(e.message || e.stack || "Unknown error").split("\n").slice(0, 25).join("\n");
  const file = e.location ? relToRun(path.join(runDir, "tests"), e.location.file) : undefined;
  return {
    message: msg,
    line: e.location?.line,
    column: e.location?.column,
    file,
    snippet: e.snippet ? stripAnsi(e.snippet) : undefined,
  };
}

/** Folds repeat-each runs of the same test into one row: passed / failed / flaky. */
export function parseReport(runDir: string, runId: string, report: JsonReport): { tests: TestResult[]; mutants: MutantResult[]; globalErrors: TestError[] } {
  const rows: TestResult[] = [];
  const mutantMap = new Map<string, MutantResult>();
  const artifactUrl = (abs?: string) => {
    const rel = relToRun(runDir, abs);
    return rel ? `/pw/artifacts/${runId}/${rel}` : undefined;
  };

  // repeat-each copies arrive as separate specs: group by project + file + title path first.
  const groups = new Map<string, { spec: JsonSpec; here: string[]; project: string; tests: JsonTest[] }>();
  const walk = (suite: JsonSuite, titles: string[]) => {
    const here = suite.title && !/\.(ts|js)$/.test(suite.title) ? [...titles, suite.title] : titles;
    for (const spec of suite.specs || []) {
      for (const t of spec.tests) {
        const key = [t.projectName, spec.file, ...here, spec.title].join("\u0000");
        const g = groups.get(key) || { spec, here, project: t.projectName, tests: [] };
        g.tests.push(t);
        groups.set(key, g);
      }
    }
    for (const child of suite.suites || []) walk(child, here);
  };
  for (const s of report.suites || []) walk(s, []);

  for (const { spec, here, project, tests } of groups.values()) {
      {
        const results = tests.flatMap((t) => t.results.map((r) => ({ r, t })));
        if (project.startsWith("mutant:")) {
          const bug = project.slice("mutant:".length);
          const m = mutantMap.get(bug) || { bug, status: "not-run" as MutantResult["status"], tests: 0 };
          m.tests += 1;
          const failed = results.some(({ r }) => r.status !== "passed" && r.status !== "skipped");
          const ran = results.some(({ r }) => r.status !== "skipped");
          if (failed) m.status = "caught";
          else if (ran && m.status === "not-run") m.status = "missed";
          mutantMap.set(bug, m);
          continue;
        }
        const runs: TestRun[] = results.map(({ r, t }, i) => ({
          status: r.status,
          duration: r.duration,
          repeat: r.repeatEachIndex ?? t.repeatEachIndex ?? i,
          error: toError(runDir, r.errors?.[0] || r.error),
        }));
        const passed = runs.filter((x) => x.status === "passed").length;
        const skipped = runs.every((x) => x.status === "skipped");
        const timedOut = runs.some((x) => x.status === "timedOut");
        let status: TestResult["status"] = "failed";
        if (skipped) status = "skipped";
        else if (passed === runs.length) status = "passed";
        else if (passed > 0) status = "flaky";
        else if (timedOut) status = "timedOut";
        const firstBad = runs.find((x) => x.status !== "passed" && x.status !== "skipped");
        // Prefer artifacts from the failing repetition; otherwise from the first one.
        const focus = results.find(({ r }) => r.status !== "passed" && r.status !== "skipped") || results[0];
        const atts = focus?.r.attachments || [];
        let log: LogEntry[] = [];
        const hubLog = atts.find((a) => a.name === "hub-log");
        if (hubLog?.body) {
          try { log = JSON.parse(Buffer.from(hubLog.body, "base64").toString("utf8")); } catch { log = []; }
        } else if (hubLog?.path) {
          try { log = JSON.parse(fs.readFileSync(hubLog.path, "utf8")); } catch { log = []; }
        }
        rows.push({
          id: crypto.createHash("sha1").update(project + "|" + spec.file + "|" + [...here, spec.title].join(" › ")).digest("hex").slice(0, 12),
          title: spec.title,
          titlePath: [...here, spec.title],
          file: spec.file,
          line: spec.line,
          project,
          status,
          runs,
          durationMs: Math.round(runs.reduce((a, x) => a + x.duration, 0) / Math.max(1, runs.length)),
          error: firstBad?.error,
          screenshots: atts.filter((a) => a.contentType.startsWith("image/") && a.path).map((a) => artifactUrl(a.path)).filter(Boolean) as string[],
          trace: artifactUrl(atts.find((a) => a.name === "trace" && a.path)?.path),
          log,
        });
      }
  }
  return {
    tests: rows,
    mutants: [...mutantMap.values()],
    globalErrors: (report.errors || []).map((e) => toError(runDir, e)!).filter(Boolean),
  };
}

function pruneRuns() {
  try {
    const dirs = fs.readdirSync(RUNS_DIR)
      .filter((d) => /^[a-f0-9]{32}$/.test(d))
      .map((d) => ({ d, t: fs.statSync(path.join(RUNS_DIR, d)).mtimeMs }))
      .sort((a, b) => b.t - a.t);
    for (const { d } of dirs.slice(KEEP_RUNS)) fs.rmSync(path.join(RUNS_DIR, d), { recursive: true, force: true });
  } catch {
    /* best effort */
  }
}

export function clearRuns() {
  fs.rmSync(RUNS_DIR, { recursive: true, force: true });
  fs.mkdirSync(RUNS_DIR, { recursive: true });
}

function rewriteImports(code: string, fileRel: string, ranges?: Array<{ start: number; end: number }>): string {
  const fromDir = path.posix.dirname(path.posix.join("tests", fileRel));
  let target = path.posix.relative(fromDir, "hub/test");
  if (!target.startsWith(".")) target = "./" + target;
  if (ranges && ranges.length) {
    let out = code;
    for (const r of [...ranges].sort((a, b) => b.start - a.start)) out = out.slice(0, r.start) + target + out.slice(r.end);
    return out;
  }
  return code.replace(/(from\s+|import\s*\(\s*)(['"])@playwright\/test\2/g, (_m, pre, q) => `${pre}${q}${target}${q}`);
}

export async function runPlaywright(opts: RunOptions): Promise<RunReport> {
  const runId = crypto.randomUUID().replace(/-/g, "");
  const runDir = path.join(RUNS_DIR, runId);
  const started = Date.now();
  const repeatEach = Math.min(Math.max(opts.repeatEach ?? 1, 1), 5);
  const preset: Preset = opts.preset || "default";
  const mutants = (opts.mutants || []).filter((m) => /^[a-z0-9-]{1,40}$/.test(m)).slice(0, 4);
  const testTimeoutMs = Math.min(opts.testTimeoutMs ?? 15000, 30000);
  const timeoutMs = Math.min(opts.timeoutMs ?? (45000 + repeatEach * 15000 + mutants.length * 10000), Number(process.env.PW_RUN_TIMEOUT_MS || 150000));

  fs.mkdirSync(path.join(runDir, "tests"), { recursive: true });
  fs.mkdirSync(path.join(runDir, "hub"), { recursive: true });
  fs.writeFileSync(path.join(runDir, "hub", "test.ts"), HUB_TEST_SOURCE);
  fs.writeFileSync(path.join(runDir, "playwright.config.ts"), buildConfig(runId, { repeatEach, preset, mutants, testTimeoutMs }));
  fs.mkdirSync(path.join(runDir, "playwright", ".auth"), { recursive: true });

  const mainRel = safeRelPath(opts.testFile);
  for (const f of opts.supportFiles || []) {
    const rel = safeRelPath(f.path);
    const abs = path.join(runDir, "tests", rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, rewriteImports(f.content, rel));
  }
  const mainAbs = path.join(runDir, "tests", mainRel);
  fs.mkdirSync(path.dirname(mainAbs), { recursive: true });
  fs.writeFileSync(mainAbs, rewriteImports(opts.code, mainRel, opts.importRanges));

  const cli = path.join(RUNNER_ROOT, "node_modules", "@playwright", "test", "cli.js");
  const env: NodeJS.ProcessEnv = {
    PATH: process.env.PATH,
    HOME: runDir,
    CI: "1",
    FORCE_COLOR: "0",
    NODE_PATH: path.join(RUNNER_ROOT, "node_modules"),
    // HOME points at the run dir, so pin the browser cache explicitly (the official image sets /ms-playwright).
    PLAYWRIGHT_BROWSERS_PATH: process.env.PLAYWRIGHT_BROWSERS_PATH || path.join(process.env.HOME || "/root", ".cache", "ms-playwright"),
    PW_TEST_HTML_REPORT_OPEN: "never",
  };
  for (const k of Object.keys(env)) if (env[k] === undefined) delete env[k];

  let stdout = "";
  let stderr = "";
  let timedOut = false;
  const exitCode: number | null = await new Promise((resolve) => {
    const child = spawn(process.execPath, [cli, "test", "--config", path.join(runDir, "playwright.config.ts")], {
      cwd: runDir, env, detached: true, stdio: ["ignore", "pipe", "pipe"],
    });
    const cap = (s: string, d: Buffer) => (s.length < 64_000 ? s + d.toString() : s);
    child.stdout.on("data", (d: Buffer) => { stdout = cap(stdout, d); });
    child.stderr.on("data", (d: Buffer) => { stderr = cap(stderr, d); });
    const timer = setTimeout(() => {
      timedOut = true;
      try { if (child.pid) process.kill(-child.pid, "SIGKILL"); } catch { /* gone */ }
    }, timeoutMs);
    child.on("close", (code) => { clearTimeout(timer); resolve(code); });
    child.on("error", (err) => { clearTimeout(timer); stderr += String(err); resolve(null); });
  });

  let parsed: ReturnType<typeof parseReport> = { tests: [], mutants: [], globalErrors: [] };
  const reportPath = path.join(runDir, "report.json");
  if (fs.existsSync(reportPath)) {
    try {
      parsed = parseReport(runDir, runId, JSON.parse(fs.readFileSync(reportPath, "utf8")));
    } catch (e) {
      parsed.globalErrors.push({ message: `Could not read the Playwright report: ${String(e)}` });
    }
  }
  if (timedOut) parsed.globalErrors.unshift({ message: `The run was stopped after ${Math.round(timeoutMs / 1000)} s (lab time limit). Look for a test that waits forever, e.g. an unawaited promise or a locator that never appears.` });
  for (const m of mutants) if (!parsed.mutants.find((x) => x.bug === m)) parsed.mutants.push({ bug: m, status: "not-run", tests: 0 });

  pruneRuns();
  const primary = parsed.tests.filter((t) => !t.project.startsWith("mutant:"));
  return {
    runId,
    ok: !timedOut && primary.length > 0 && primary.every((t) => t.status === "passed") && parsed.globalErrors.length === 0,
    exitCode,
    timedOut,
    durationMs: Date.now() - started,
    ...parsed,
    stdout: stripAnsi(stdout).slice(-8000),
    stderr: stripAnsi(stderr).slice(-8000),
  };
}
